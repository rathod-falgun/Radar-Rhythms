def get_observations_for_region(region_id: str, only_processed: bool = True) -> List[Dict[str, Any]]:
    """Returns data-driven observations for the given region."""
    if region_id == "majuli":
        obs_list = MAJULI_OBSERVATIONS
    elif region_id == "barpeta":
        obs_list = BARPETA_OBSERVATIONS
    elif only_processed:
        return []
    else:
        obs_list = NISAR_OBSERVATION_CATALOG

    if only_processed:
        return [obs for obs in obs_list if obs.get("is_processed") and obs.get("status") == "PROCESSED_AVAILABLE"]
    return obs_list

def get_observation_by_date(date_str: str) -> Dict[str, Any]:
    for obs in NISAR_OBSERVATION_CATALOG:
        if obs["date"] == date_str:
            return obs
    return NISAR_OBSERVATION_CATALOG[3]  # Default to event observation 2026-07-09

def get_region_by_id(region_id: str) -> Dict[str, Any]:
    for reg in STUDY_REGIONS:
        if reg["id"] == region_id:
            return reg
    return STUDY_REGIONS[0]  # Default to Kaziranga

